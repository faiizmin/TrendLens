-- Clerk subject mapping, atomic first-company onboarding, and least-privilege
-- Neon application permissions. Review and apply only after 001_initial_schema.sql.
BEGIN;

DO $$
BEGIN
  CREATE ROLE trendlens_app NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
EXCEPTION WHEN duplicate_object THEN
  ALTER ROLE trendlens_app NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
END
$$;

-- This dedicated group role must never inherit another role's privileges. It
-- may have member logins after setup (roleid = trendlens_app), but cannot itself
-- be a member of an administrative or other privilege-bearing role.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_auth_members WHERE member = 'trendlens_app'::regrole) THEN
    RAISE EXCEPTION 'trendlens_app is already a member of another role; remove that membership and review the role before retrying';
  END IF;
END
$$;

REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM trendlens_app;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM trendlens_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
REVOKE CREATE ON SCHEMA public FROM trendlens_app;
GRANT USAGE ON SCHEMA public TO trendlens_app;

-- Auth/session resolution and the one-time onboarding flow only. Manufacturing
-- tables intentionally receive no privileges, so there is no data API surface.
GRANT SELECT, INSERT ON users, companies, company_memberships TO trendlens_app;
REVOKE ALL ON production_records, downtime_events, quality_records FROM trendlens_app;

-- An owner account can provision only one company in this initial model.
CREATE UNIQUE INDEX IF NOT EXISTS company_owner_single_company
  ON company_memberships(user_id) WHERE role = 'owner';

DROP POLICY IF EXISTS companies_member_read ON companies;
DROP POLICY IF EXISTS companies_owner_onboarding_insert ON companies;
DROP POLICY IF EXISTS users_self_read ON users;
DROP POLICY IF EXISTS users_clerk_onboarding_insert ON users;
DROP POLICY IF EXISTS memberships_self_read ON company_memberships;
DROP POLICY IF EXISTS memberships_owner_onboarding_insert ON company_memberships;
DROP POLICY IF EXISTS production_records_member_read ON production_records;
DROP POLICY IF EXISTS downtime_events_member_read ON downtime_events;
DROP POLICY IF EXISTS quality_records_member_read ON quality_records;

-- The original policies depend on this function, so remove the policies before
-- dropping it. A direct DROP earlier in this migration fails on PostgreSQL.
DROP FUNCTION IF EXISTS app_can_access_company(uuid);

-- Subject and ids are set with SET LOCAL only inside server-controlled Neon
-- transactions, after Clerk verification and membership resolution. Local
-- settings are cleared by PostgreSQL at transaction end (including pooled
-- connections), so context cannot bleed into a later request.
CREATE POLICY users_self_read ON users FOR SELECT TO trendlens_app
  USING (auth_provider = 'clerk'
    AND auth_subject = NULLIF(current_setting('app.current_clerk_subject', true), ''));
CREATE POLICY users_clerk_onboarding_insert ON users FOR INSERT TO trendlens_app
  WITH CHECK (auth_provider = 'clerk'
    AND auth_subject = NULLIF(current_setting('app.current_clerk_subject', true), ''));

CREATE POLICY memberships_self_read ON company_memberships FOR SELECT TO trendlens_app
  USING (user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid);
CREATE POLICY memberships_owner_onboarding_insert ON company_memberships FOR INSERT TO trendlens_app
  WITH CHECK (
    user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid
    AND company_id = NULLIF(current_setting('app.current_company_id', true), '')::uuid
    AND role = 'owner'
  );

CREATE POLICY companies_member_read ON companies FOR SELECT TO trendlens_app
  USING (
    id = NULLIF(current_setting('app.current_company_id', true), '')::uuid
    AND EXISTS (
      SELECT 1 FROM company_memberships AS membership
      WHERE membership.company_id = companies.id
        AND membership.user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid
    )
  );
-- The ID is generated by the server and set transaction-locally before the
-- insert, allowing INSERT ... RETURNING without a pre-existing membership.
CREATE POLICY companies_onboarding_returning ON companies FOR SELECT TO trendlens_app
  USING (
    id = NULLIF(current_setting('app.current_company_id', true), '')::uuid
    AND id = NULLIF(current_setting('app.onboarding_company_id', true), '')::uuid
  );
CREATE POLICY companies_owner_onboarding_insert ON companies FOR INSERT TO trendlens_app
  WITH CHECK (
    id = NULLIF(current_setting('app.current_company_id', true), '')::uuid
    AND id = NULLIF(current_setting('app.onboarding_company_id', true), '')::uuid
    AND NULLIF(current_setting('app.current_user_id', true), '') IS NOT NULL
    AND NOT EXISTS (
      SELECT 1 FROM company_memberships AS membership
      WHERE membership.user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid
    )
  );

-- These policies remain ready for later endpoints. The application role has no
-- grants on the manufacturing tables in this migration.
CREATE POLICY production_records_member_read ON production_records FOR SELECT TO trendlens_app
  USING (company_id = NULLIF(current_setting('app.current_company_id', true), '')::uuid
    AND EXISTS (SELECT 1 FROM company_memberships membership
      WHERE membership.company_id = production_records.company_id
        AND membership.user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid));
CREATE POLICY downtime_events_member_read ON downtime_events FOR SELECT TO trendlens_app
  USING (company_id = NULLIF(current_setting('app.current_company_id', true), '')::uuid
    AND EXISTS (SELECT 1 FROM company_memberships membership
      WHERE membership.company_id = downtime_events.company_id
        AND membership.user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid));
CREATE POLICY quality_records_member_read ON quality_records FOR SELECT TO trendlens_app
  USING (company_id = NULLIF(current_setting('app.current_company_id', true), '')::uuid
    AND EXISTS (SELECT 1 FROM company_memberships membership
      WHERE membership.company_id = quality_records.company_id
        AND membership.user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid));

COMMIT;
